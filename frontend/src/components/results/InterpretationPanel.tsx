function paragraphs(text: string): string[] {
  return text
    .split(/\n\s*\n|\n/)
    .map((p) => p.trim())
    .filter(Boolean);
}

export function InterpretationPanel({ result, loading }: { result: AnalysisResponse | null; loading: boolean }) {
  return (
    <section aria-labelledby="interpretation-title" className="panel p-4 sm:p-5" aria-busy={loading}>
      <header className="mb-4">
        <h2 id="interpretation-title" className="panel-title flex items-center gap-2">
          <BrainCircuit className="h-3.5 w-3.5" aria-hidden="true" />
          AI-assisted interpretation
        </h2>
        <p className="mt-1 text-sm text-muted">Deterministic explanation generated by the backend. No external AI model is called.</p>
      </header>

      {loading && !result ? (
        <LoadingSkeleton lines={4} className="h-4 w-full" />
      ) : !result ? (
        <EmptyState title="No explanation yet" description="Run an analysis to see the backend's plain-language explanation, assumptions and warnings." />
      ) : (
        <div className="space-y-4">
          <div className="space-y-3 text-sm leading-relaxed text-ink/90">
            {paragraphs(result.explanation).map((p, i) => (
              <p key={i}>{p}</p>
            ))}
          </div>
          <div className="grid gap-4 lg:grid-cols-2">
            <AssumptionsPanel assumptions={result.assumptions} />
            <WarningsPanel warnings={result.warnings} />
          </div>
          <div className="flex gap-3 rounded-xl border border-danger/25 bg-danger/[0.05] p-4">
            <ShieldAlert className="mt-0.5 h-4 w-4 shrink-0 text-danger" aria-hidden="true" />
            <div>
              <h3 className="text-sm font-semibold text-ink">Disclaimer</h3>
              <p className="mt-1 text-sm leading-relaxed text-muted">{result.disclaimer}</p>
            </div>
          </div>
        </div>
      )}

      <div className="mt-5 border-t border-line/10 pt-4">
        <h3 className="mb-3 text-sm font-semibold text-ink">How to read this</h3>
        <dl className="grid gap-3 sm:grid-cols-2 xl:grid-cols-3">
          {HOW_TO_READ.map((t) => (
            <div key={t.title} className="rounded-xl border border-line/10 bg-elevated/30 p-3">
              <dt className="text-xs font-semibold text-accent">{t.title}</dt>
              <dd className="mt-1 text-xs leading-relaxed text-muted">{t.body}</dd>
            </div>
          ))}
        </dl>
      </div>
    </section>
  );
}
